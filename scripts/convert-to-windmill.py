#!/usr/bin/env python3
"""Convert dagnats recipes into Windmill flow skeletons.

This is the mechanical half of `docs/migrate-to-windmill.md`: it reads a
client's dagnats recipes and emits, per recipe, a WAC flow directory with one
step per source step, plus scripts where the mapping is unambiguous.

It does NOT claim a working port. Three things are deliberately left as TODOs,
because guessing them would produce a flow that looks migrated and is not:

  * `transform.json` expressions — jq is not JavaScript. The expression is
    carried verbatim into a comment so a human rewrites it with intent.
  * `condition` predicates — same reason.
  * Any step type not in the mapping table below.

It never writes into `automation/windmill/`. Output goes to a staging directory
(default `<client>/converted-windmill/`) so a half-converted flow can never be
pushed by accident. Use --force to overwrite a previous staging run only.

Usage:
    ./scripts/convert-to-windmill.py <client>                    # staging dir
    ./scripts/convert-to-windmill.py <client> --out DIR
    TURVEZ_OPS_DIR=../turvez-ops ./scripts/convert-to-windmill.py acme
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE.parent

# What each source step becomes, and whether a human must finish it.
MAPPING = {
    "http.request": ("script", False, "HTTP call — method/url/headers/body map 1:1"),
    "transform.json": ("script", True, "jq expression must be rewritten as TS/Python"),
    "condition": ("branch", True, "predicate must be rewritten as if/else"),
    "skip_if": ("branch", True, "predicate must be rewritten as if/else"),
    "map": ("forloop", True, "for-loop / parallel map over the input array"),
    "map.json": ("forloop", True, "for-loop / parallel map over the input array"),
    "delay": ("sleep", False, "sleep step"),
    "sleep": ("sleep", False, "sleep step"),
    "request.approval": ("approval", False, "approval step or form + suspend/resume"),
    "approval": ("approval", False, "approval step or form + suspend/resume"),
    "notify.webhook": ("script", False, "HTTP POST to the webhook URL"),
    "notify.slack": ("script", False, "HTTP POST to the Slack URL"),
    "notify.telegram": ("script", False, "HTTP POST to the Telegram API"),
    "notify.discord": ("script", False, "HTTP POST to the Discord webhook"),
    "dlq.check": ("script", True, "read DLQ depth via API/CLI equivalent"),
    "llm.complete": ("script", True, "call the model from the script (see docs/observability.md)"),
}


def load_recipe(path):
    try:
        return json.loads(path.read_text())
    except Exception as exc:
        sys.stderr.write("skip %s: %s\n" % (path, exc))
        return None


def slug(value, fallback):
    out = re.sub(r"[^a-z0-9_]+", "_", (value or "").lower()).strip("_")
    return out or fallback


def metadata_pairs(meta):
    """metadata is map[string]string; carry it through as literal strings."""
    lines = []
    for key in sorted(meta or {}):
        lines.append("//   %s = %s" % (key, meta[key]))
    return lines


def step_notes(step, kind, needs_human, why):
    notes = []
    notes.append("// step id: %s" % step.get("id", "?"))
    notes.append("// source task: %s  ->  %s" % (step.get("task", "?"), kind))
    notes.append("// %s" % why)
    deps = step.get("depends_on") or []
    if deps:
        notes.append("// depends_on: %s" % ", ".join(str(d) for d in deps))
    meta = step.get("metadata") or {}
    if meta:
        notes.append("// metadata:")
        notes.extend(metadata_pairs(meta))
    if needs_human:
        notes.append("// TODO(human): this step does not translate mechanically.")
    return notes


def emit_flow(recipe, client):
    """One module per recipe, with the flow graph inlined as a comment map.

    WAC's real shape is a `*.flow/` directory with flow.yaml + per-module files.
    Emitting the structure keeps the manifest honest; the scripts are skeletons
    with the source metadata attached, not runnable ports.
    """
    name = recipe.get("name") or "unnamed"
    steps = recipe.get("steps") or []

    files = []
    flow_yaml = ["summary: '%s' (converted from dagnats)" % name,
                 "description: >-",
                 "  Skeleton generated by scripts/convert-to-windmill.py from",
                 "  automation/dagnats. Steps marked TODO need a human rewrite.",
                 "value:",
                 "  modules:"]
    if not steps:
        flow_yaml.append("    []")
    for step in steps:
        sid = slug(step.get("id"), "step")
        task = step.get("task", "")
        kind, needs_human, why = MAPPING.get(task, ("script", True, "unmapped task"))
        flow_yaml.append("    - id: %s" % sid)
        flow_yaml.append("      summary: '%s (%s)'" % (step.get("id", sid), task))
        flow_yaml.append("      value:")
        flow_yaml.append("        type: rawscript")
        flow_yaml.append("        language: deno")
        flow_yaml.append("        content: '!inline %s.ts'" % sid)
    flow_yaml.append("  # source graph (dagnats depends_on order):")
    for step in steps:
        deps = step.get("depends_on") or []
        flow_yaml.append("  #   %s <- %s" % (step.get("id", "?"),
                                             ", ".join(str(d) for d in deps) or "root"))

    files.append(("flow.yaml", "\n".join(flow_yaml) + "\n"))

    for step in steps:
        sid = slug(step.get("id"), "step")
        task = step.get("task", "")
        kind, needs_human, why = MAPPING.get(task, ("script", True, "unmapped task"))
        body = ["// Converted skeleton — NOT a port.",
                "// See clients/%s/converted-windmill/REPORT.md" % client,
                ""]
        body.extend(step_notes(step, kind, needs_human, why))
        body.append("")
        if task == "transform.json":
            expr = (step.get("metadata") or {}).get("expression", "")
            body.append("// jq expression carried verbatim (jq is not JavaScript):")
            body.append("// %s" % expr)
            body.append("export function main(input: any) {")
            body.append("  // TODO(human): express the jq above in TypeScript.")
            body.append("  return input;")
            body.append("}")
        elif task == "http.request":
            body.append("export async function main(input: any) {")
            body.append("  // TODO: fill from the metadata above (method/url/headers/body).")
            body.append("  const res = await fetch('https://example.invalid/', { method: 'GET' });")
            body.append("  return await res.json();")
            body.append("}")
        elif task in ("condition", "skip_if"):
            body.append("export function main(input: any) {")
            body.append("  // TODO(human): rewrite the predicate as a boolean.")
            body.append("  return true;")
            body.append("}")
        else:
            body.append("export function main(input: any) {")
            body.append("  // TODO(human): %s" % why)
            body.append("  return input;")
            body.append("}")
        files.append(("%s.ts" % sid, "\n".join(body) + "\n"))

    return name, files, steps


def build_report(client, converted, skipped):
    L = ["# Conversion report — %s" % client, "",
         "Generated by `scripts/convert-to-windmill.py`. This is a **skeleton**, not a port.",
         "", "## Summary", "",
         "- recipes converted: %d" % len(converted),
         "- recipes skipped: %d" % len(skipped), ""]

    if converted:
        L += ["## Per recipe", ""]
        for name, files, steps in converted:
            todo = 0
            for step in steps:
                task = step.get("task", "")
                _, needs_human, _ = MAPPING.get(task, ("script", True, ""))
                if needs_human:
                    todo += 1
            L.append("- **%s** — %d steps, %d need a human rewrite" % (name, len(steps), todo))
        L.append("")

    if skipped:
        L += ["## Skipped", ""]
        for path, reason in skipped:
            L.append("- `%s` — %s" % (path, reason))
        L.append("")

    L += ["## What the converter will not do", "",
          "1. **jq → TypeScript.** The expression is carried in a comment. Rewrite it",
          "   with intent; a wrong translation that looks migrated is worse than a TODO.",
          "2. **Condition predicates.** Same reason.",
          "3. **Custom Go handlers.** If a recipe used one, it appears as an unmapped",
          "   step. Each is the long pole of a migration — budget it explicitly.",
          "",
          "## Before pushing anything", "",
          "```bash",
          "# 1. finish the TODOs above, then lint locally",
          "wmill flow preview <flow-dir>",
          "# 2. push ONE flow at a time. Never `wmill sync push` (it deletes",
          "#    remote items missing locally).",
          'wmill flow push <flow-dir> "f/%s/<flow>"' % client,
          "```", "",
          "Then delete the converted `automation/dagnats/` directory only after the",
          "flow is green in production — see docs/client-spine.md, engine change."]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Convert dagnats recipes to Windmill skeletons.")
    ap.add_argument("client")
    ap.add_argument("--out", help="staging directory (default: <client>/converted-windmill)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing staging dir")
    args = ap.parse_args()

    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", args.client):
        raise SystemExit("bad client id: %s" % args.client)

    root = Path(os.environ.get("TURVEZ_OPS_DIR") or TEMPLATE).resolve()
    cdir = root / "clients" / args.client
    if not cdir.is_dir():
        raise SystemExit("no client %r under %s" % (args.client, root / "clients"))

    src = cdir / "automation" / "dagnats"
    recipes = sorted(src.glob("*.json")) if src.is_dir() else []
    if not recipes:
        raise SystemExit("no dagnats recipes under %s" % src)

    out = Path(args.out) if args.out else cdir / "converted-windmill"
    if out.exists() and any(out.iterdir()) and not args.force:
        raise SystemExit("%s already has content — pass --force to overwrite" % out)

    converted = []
    skipped = []
    for path in recipes:
        recipe = load_recipe(path)
        if recipe is None:
            skipped.append((path.name, "unreadable JSON"))
            continue
        name, files, steps = emit_flow(recipe, args.client)
        converted.append((name, files, steps))
        target = out / slug(name.split(".")[-1], path.stem)
        target.mkdir(parents=True, exist_ok=True)
        for fname, content in files:
            (target / fname).write_text(content)

    (out / "REPORT.md").write_text(build_report(args.client, converted, skipped))
    print("converted %d recipe(s) -> %s" % (len(converted), out))
    print("read %s/REPORT.md before doing anything else" % out)
    if skipped:
        print("skipped %d (see report)" % len(skipped))
    return 0


if __name__ == "__main__":
    sys.exit(main())
